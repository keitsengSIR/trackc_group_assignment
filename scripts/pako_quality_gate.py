"""Pako's auditable CI quality gate for COMP 441 Track C.

Coverage comes from a current coverage.py/pytest-cov Cobertura XML result.
Mutation evidence is intentionally NOT inferred from a stale repository file.

A mutation JSON file must contain score, commit_sha, tool, and created_at_utc;
commit_sha must equal the tested GitHub commit when mutation enforcement is on.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from xml.etree import ElementTree


def load_policy(path: str) -> dict:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    for key in ("minimum_line_coverage", "minimum_mutation_score"):
        value = data.get(key)
        if type(value) not in (float, int) or not 0 <= value <= 100:
            raise ValueError(f"{key} must be a number from 0 to 100")
    if type(data.get("enforce_mutation")) is not bool:
        raise ValueError("enforce_mutation must be a boolean")
    return data


def read_line_coverage(path: str) -> float:
    """Return actual Cobertura line rate as a percentage."""
    root = ElementTree.parse(path).getroot()
    if root.tag != "coverage":
        raise ValueError("Expected <coverage> as the XML root")
    rate = float(root.attrib["line-rate"])
    if not 0 <= rate <= 1:
        raise ValueError("coverage line-rate must be within 0..1")
    return rate * 100


def read_mutation_score(path: str, expected_commit: str) -> float:
    """Require same-commit, fresh mutation evidence; never manufacture a score."""
    if not expected_commit:
        raise ValueError("Expected commit SHA is required when mutation enforcement is enabled")
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if data.get("commit_sha") != expected_commit:
        raise ValueError("Mutation evidence commit_sha differs from the tested commit")
    for field in ("tool", "created_at_utc"):
        if not isinstance(data.get(field), str) or not data[field].strip():
            raise ValueError(f"Mutation evidence requires {field}")
    # The test owner must calculate and justify the score from a new mutation run.
    score = data.get("score")
    if type(score) not in (int, float) or not 0 <= score <= 100:
        raise ValueError("Mutation score must be numeric 0..100")
    return float(score)


def evaluate(policy_path: str, coverage_xml: str, mutation_json: str | None = None,
             commit_sha: str | None = None) -> tuple[bool, list[str]]:
    policy = load_policy(policy_path)
    messages = []
    actual_line = read_line_coverage(coverage_xml)
    required_line = policy["minimum_line_coverage"]
    coverage_ok = actual_line >= required_line
    messages.append(f"Line coverage: {actual_line:.2f}% (required {required_line:.2f}%): {'PASS' if coverage_ok else 'FAIL'}")
    if not policy["enforce_mutation"]:
        messages.append("Mutation gate: NOT YET ENFORCED — pending Maano's measured same-commit v2 mutation results")
        return coverage_ok, messages
    if not mutation_json:
        return False, messages + ["Mutation gate: FAIL — no mutation JSON path provided"]
    try:
        score = read_mutation_score(mutation_json, commit_sha or os.environ.get("GITHUB_SHA", ""))
    except (FileNotFoundError, ValueError, json.JSONDecodeError) as exc:
        return False, messages + [f"Mutation gate: FAIL — {exc}"]
    mutation_ok = score >= policy["minimum_mutation_score"]
    messages.append(f"Mutation score: {score:.2f}% (required {policy['minimum_mutation_score']:.2f}%): {'PASS' if mutation_ok else 'FAIL'}")
    return coverage_ok and mutation_ok, messages


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Track C CI quality gate")
    p.add_argument("--policy", default="docs/pako/quality_gate_policy.json")
    p.add_argument("--coverage-xml", default="coverage.xml")
    p.add_argument("--mutation-json", default="", help="Same-commit evidence generated by mutation step")
    p.add_argument("--commit-sha", default="", help="Commit under test; defaults to GITHUB_SHA")
    args = p.parse_args(argv)
    try:
        passed, messages = evaluate(args.policy, args.coverage_xml,
                                    args.mutation_json or None, args.commit_sha or None)
    except (OSError, ValueError, KeyError, ElementTree.ParseError, json.JSONDecodeError) as exc:
        print(f"QUALITY GATE ERROR: {exc}", file=sys.stderr)
        return 2
    for message in messages:
        print(message)
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
